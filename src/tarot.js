const majorCodes=Array.from({length:22},(_,i)=>`m${String(i).padStart(2,'0')}`);
const major=majorSeed.map((row,id)=>({
  id,code:majorCodes[id],arcana:'major',suit:null,rank:id,name:row[0],en:row[1],keywords:row[2],
  upright:row[3],reversed:row[4],advice:row[5],symbolism:row[6],image:`/tarot-rws/${majorCodes[id]}.jpg`
}));
const minor=MINOR_RWS.map((card,index)=>({...card,id:22+index}));

export const TAROT_DECK=[...major,...minor];
export const MAJOR_ARCANA=major;

function browserRandom(){
  if(globalThis.crypto?.getRandomValues){
    const value=new Uint32Array(1);
    globalThis.crypto.getRandomValues(value);
    return value[0]/4294967296;
  }
  return Math.random();
}

function drawUniqueCards(count,randomSource){
  const pool=[...TAROT_DECK],result=[];
  while(result.length<count){
    const index=Math.min(pool.length-1,Math.floor(randomSource()*pool.length));
    const [card]=pool.splice(index,1);
    result.push({card,reversed:randomSource()>=0.5});
  }
  return result;
}

export function prepareTarotFan(size=18,randomSource=browserRandom){
  if(!Number.isInteger(size) || size < 3 || size > TAROT_DECK.length) {
    throw new RangeError(`타로 선택지는 3~${TAROT_DECK.length}장 사이여야 합니다.`);
  }
  return drawUniqueCards(size,randomSource);
}

export function drawTarot(count,randomSource=browserRandom){
  if(![1,3].includes(count)) throw new RangeError('타로는 1장 또는 3장만 뽑을 수 있습니다.');
  return drawUniqueCards(count,randomSource);
}

const POSITIONS={
  today:['오늘의 메시지'],
  question:['현재 상황','장애물','조언'],
  love:['나의 마음','상대/관계의 흐름','관계를 위한 조언'],
  money:['현재 흐름','기회','주의할 점'],
  career:['현재 일의 흐름','성장 기회','실행 조언']
};

function contextualAdvice(mode,card){
  const suffix={
    love:'연애에서는 상대의 마음을 단정하기보다 대화와 행동에서 확인되는 사실을 함께 보세요.',
    money:'재물에서는 수입 기대보다 비용·조건·손실 가능성을 숫자로 확인한 뒤 결정하세요.',
    career:'직업에서는 역할·성과·기한처럼 실제로 조정할 수 있는 요소부터 행동으로 옮기세요.',
    question:'질문에 대한 정답이라기보다 놓치고 있던 관점을 확인하는 도구로 활용하세요.',
    today:'오늘 하루에 적용할 수 있는 작은 행동 하나로 메시지를 바꿔보세요.'
  };
  return `${card.advice} ${suffix[mode]||suffix.question}`;
}

export function interpretSpread(mode,draw){
  const positions=POSITIONS[mode]||POSITIONS.question;
  if(draw.length!==positions.length) throw new RangeError(`${mode} 스프레드는 ${positions.length}장이 필요합니다.`);
  return draw.map((item,index)=>{
    const meaning=item.reversed?item.card.reversed:item.card.upright;
    const advice=contextualAdvice(mode,item.card);
    return {
      position:positions[index],
      card:item.card,
      reversed:item.reversed,
      orientation:item.reversed?'역방향':'정방향',
      meaning,
      symbolism:item.card.symbolism,
      advice,
      text:`${item.card.name}(${item.card.en}) ${item.reversed?'역방향':'정방향'}의 핵심은 ${item.card.keywords}입니다. ${meaning} 그림에서는 ${item.card.symbolism} 현실적으로는 ${advice} 타로는 미래를 확정하는 예언이 아니라 질문을 다른 각도에서 살펴보기 위한 상징적 참고 도구입니다.`
    };
  });
}
